/**
 * A couple of bookings so My Bookings and the booked-details screen have something to
 * show in development — one upcoming, one already played.
 *
 * Built relative to `at` rather than stored flat, so the upcoming one never drifts into
 * the past while the app sits open.
 */
export function exampleBookings(at: Date): Booking[] {
  const hourMs = 3_600_000;
  const upcomingStart = new Date(at.getTime() + 2 * 24 * hourMs);
  upcomingStart.setUTCHours(16, 0, 0, 0); // 9 PM PKT
  const pastStart = new Date(at.getTime() - 6 * 24 * hourMs);
  pastStart.setUTCHours(14, 0, 0, 0); // 7 PM PKT

  const make = (
    id: string,
    courtId: string,
    venueId: string,
    start: Date,
    status: Booking['status'],
    courtTotal: Rupees,
    mode: Booking['paymentMode'],
  ): Booking => {
    const breakdown = calculatePayment(courtTotal, mode);
    return {
      id,
      intentId: `seed-${id}`,
      courtId,
      venueId,
      userId: CURRENT_USER_ID,
      teamId: null,
      startAt: start.toISOString(),
      endAt: new Date(start.getTime() + hourMs).toISOString(),
      status,
      total: breakdown.total,
      paidOnline: breakdown.payNow,
      dueAtVenue: breakdown.dueAtVenue,
      paymentMode: mode,
      provider: 'jazzcash',
      source: 'app',
      cancellationPolicy: STANDARD_POLICY,
      code: { 'booking-seed-upcoming': 'MK4T2P', 'booking-seed-cricket': 'TB9XQ4' }[id] ?? 'RQ7YB3',
      customer: null,
      createdAt: new Date(at.getTime() - hourMs).toISOString(),
    };
  };

  // A tape-ball cage at 11 PM: the late slot is the normal one for cricket here, not an
  // edge case (docs/01 §3 — midnight-to-sehri play through Ramadan).
  const cricketStart = new Date(at.getTime() + 3 * 24 * hourMs);
  cricketStart.setUTCHours(18, 0, 0, 0); // 11 PM PKT

  return [
    make(
      'booking-seed-upcoming',
      'court-pr-1',
      'venue-padel-republic',
      upcomingStart,
      'confirmed',
      5500,
      'deposit',
    ),
    make(
      'booking-seed-cricket',
      'court-dg-1',
      'venue-the-dugout',
      cricketStart,
      'confirmed',
      1800,
      'deposit',
    ),
    make(
      'booking-seed-past',
      'court-fr-1',
      'venue-fr-sports-johar',
      pastStart,
      'completed',
      1900,
      'full_prepay',
    ),
  ];
}

