/**
 * The seed feed is anchored to today rather than a fixed calendar date.
 *
 * A hard-coded date rots: within a week every seeded match reads "20 Sep" instead of
 * "Tonight", and the screens stop exercising the relative-date formatting they are built
 * around. Anchoring to the current PKT day keeps the feed looking like a live one.
 */
export const SEED_EPOCH = new Date();

/**
 * An instant `minutes` in the past. Chat and notification timestamps use this rather than
 * a wall-clock hour: a seeded 9:58 AM message is in the *future* before 10 AM, and
 * relative formatting would render every thread as "Just now".
 */
export function seedAgo(minutes: number): string {
  return new Date(SEED_EPOCH.getTime() - minutes * 60_000).toISOString();
}

/** Builds an ISO instant `days` from the epoch at the given PKT wall-clock hour. */
export function seedAt(days: number, hour: number, minute = 0): string {
  const date = new Date(SEED_EPOCH);
  date.setUTCDate(date.getUTCDate() + days);
  // PKT is UTC+5, so the UTC hour is the wall-clock hour minus five.
  date.setUTCHours(hour - 5, minute, 0, 0);
  return date.toISOString();
}

